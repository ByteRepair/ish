// Runs every case in sse4_cases.h on this machine's x86-64 CPU and writes
// what each gave, as sse4_expected.h, to stdout. Given case names, prints
// those cases' inputs and outputs instead, to set beside engine_test's
// account of what blink gave. Built and run by sse4_oracle.sh; needs an
// x86-64 CPU with SSE4.2, or Rosetta 2.
#include <stdlib.h>
#include <sys/mman.h>
#include "sse4_cases.h"

#ifndef MAP_JIT
#define MAP_JIT 0
#endif

static uint8_t *code;

static void run(const struct sse4_case *c, struct sse4_state *s) {
    size_t n = 0;
    memcpy(code + n, sse4_prologue, sizeof(sse4_prologue));
    n += sizeof(sse4_prologue);
    memcpy(code + n, c->bytes, c->n);
    n += c->n;
    memcpy(code + n, sse4_epilogue, sizeof(sse4_epilogue));
    n += sizeof(sse4_epilogue);
    code[n] = 0xc3;  // ret
    __builtin___clear_cache((char *) code, (char *) code + n + 1);
    ((void (*)(struct sse4_state *)) code)(s);
}

int main(int argc, char **argv) {
    code = mmap(NULL, 4096, PROT_READ | PROT_WRITE | PROT_EXEC, MAP_PRIVATE | MAP_ANONYMOUS | MAP_JIT, -1, 0);
    if (code == MAP_FAILED) {
        perror("mmap");
        return 1;
    }
    static struct sse4_case cases[SSE4_MAX_CASES];
    int n = sse4_cases(cases);

    if (argc > 1) {
        for (int i = 0; i < n; i++) {
            for (int a = 1; a < argc; a++) {
                if (strcmp(cases[i].name, argv[a]) != 0)
                    continue;
                printf("%s\n", cases[i].name);
                for (int j = 0; j < SSE4_INPUTS; j++) {
                    struct sse4_state s = {0};
                    sse4_input(j, &s);
                    sse4_print("in ", j, &cases[i], &s);
                    run(&cases[i], &s);
                    sse4_print("out", j, &cases[i], &s);
                }
            }
        }
        return 0;
    }

    printf("// Generated by tests/unit/sse4_oracle.sh from what an x86-64 CPU gave\n");
    printf("// for each case in sse4_cases.h. Do not edit.\n");
    printf("static const struct { const char *name; uint64_t hash; } sse4_expected[] = {\n");
    for (int i = 0; i < n; i++) {
        uint64_t hash = SSE4_HASH_SEED;
        for (int j = 0; j < SSE4_INPUTS; j++) {
            struct sse4_state s = {0};
            sse4_input(j, &s);
            run(&cases[i], &s);
            hash = sse4_hash(hash, &cases[i], &s);
        }
        printf("    {\"%s\", %#018llxull},\n", cases[i].name, (unsigned long long) hash);
    }
    printf("};\n");
    return 0;
}
